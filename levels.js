  // Explicit corridor plans keep the larger authored maps readable. Nothing is random.
  function layout(w, h, paths, marks) {
    const rows = Array.from({ length: h }, () => Array(w).fill('%'));
    for (const points of paths) {
      for (let n = 1; n < points.length; n++) {
        let [x, y] = points[n - 1];
        const [tx, ty] = points[n];
        if (x !== tx && y !== ty) throw new Error('Corridors must follow the grid');
        const dx = Math.sign(tx - x), dy = Math.sign(ty - y);
        rows[y][x] = '.';
        while (x !== tx || y !== ty) { x += dx; y += dy; rows[y][x] = '.'; }
      }
    }
    for (const [x, y, tile] of marks) rows[y][x] = tile;
    return rows.map((row) => row.join(''));
  }
